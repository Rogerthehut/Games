"""
Builds src/engine/little-art-traced.ts from traced pictures (see trace.py) and a short description of each picture: which traced areas are numbered,
what scene to put behind them, and the palette. Run:  python3 tools/art/build.py  (after tracing into /tmp/art/*.json, or wherever TRACED points).
"""
import json, os, sys

TRACED = os.environ.get("TRACED", "/tmp/claude-0/trace")
OUT = os.path.join(os.path.dirname(__file__), "../../src/engine/little-art-traced.ts")
SKY = "#bfe6f7"

def circ(cx, cy, r): return f"M{cx-r} {cy}a{r} {r} 0 1 0 {2*r} 0a{r} {r} 0 1 0 {-2*r} 0z"
def cloud(x, y, s=1.0):
    p = lambda a, b: f"{x + a * s:.1f} {y + b * s:.1f}"
    return f"M{p(-14,4)}C{p(-20,4)} {p(-20,-6)} {p(-11,-6)}C{p(-10,-14)} {p(2,-15)} {p(4,-8)}C{p(10,-14)} {p(20,-9)} {p(17,-1)}C{p(24,0)} {p(23,8)} {p(15,6)}C{p(15,10)} {p(-12,10)} {p(-14,4)}z"

PICTURES = []

def dino():
    d = json.load(open(f"{TRACED}/dino.json"))
    by = {r["id"]: r for r in d["regions"]}
    body = [by[2]["d"], by[42]["d"], by[47]["d"]]
    return {
        "id": "brontosaurus", "name": "a long-necked dinosaur",
        "palette": {1: SKY, 2: "#f5dc63", 3: "#e9e4fb", 4: "#7fd36a", 5: "#6cc46a", 6: "#f782a9"},
        "regions": [
            {"d": "M0 0H100V100H0z", "n": 1, "at": [8, 8]},
            {"d": circ(88, 13, 7.5), "n": 2},
            {"d": cloud(66, 22, 1.0), "n": 3}, {"d": cloud(24, 8, 0.6), "n": 3},
            {"d": "M0 84C22 79 70 90 100 82V100H0z", "n": 4, "at": [14, 94]},
            {"d": body[0], "n": 5, "plain": True}, {"d": body[1], "n": 5, "plain": True}, {"d": body[2], "n": 5, "plain": True},
            *({"d": circ(x, y, 2.6), "n": 6} for x, y in [(8, 92), (50, 95), (84, 91), (94, 95)]),
        ],
        "decor": [{"d": d["lines"], "fill": "#121522", "w": 0}],
    }
PICTURES.append(dino)

def main():
    items = [p() for p in PICTURES]
    ts = ['import type { ColourArt } from "./little-art";', "", "/** Pictures traced from line art and photos by tools/art. Generated by tools/art/build.py: edit the tools, not this file. */", "export const COLOUR_ART_TRACED: ColourArt[] = ["]
    for it in items:
        ts.append("  " + json.dumps(it, separators=(",", ":")) + ",")
    ts.append("];\n")
    open(OUT, "w").write("\n".join(ts)); print(f"wrote {len(items)} pictures, {os.path.getsize(OUT)//1024} KB")

if __name__ == "__main__": main()
