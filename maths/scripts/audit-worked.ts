/**
 * Writes docs/WORKED_EXAMPLES.md: for every maths topic, how often a question comes with a picture (a figure with the question, or the
 * method drawn in its solution). Re-run after adding pictures:  npx tsx scripts/audit-worked.ts   (or: npm run audit:worked)
 */
import { writeFileSync } from "node:fs";
import { SKILLS } from "../src/curriculum";
import { mulberry32 } from "../src/engine/rng";

const rows: { id: string; name: string; year: number; strand: string; q: number; fig: number; worked: number; any: number }[] = [];
for (const s of SKILLS) {
  let fig = 0, worked = 0, any = 0, n = 0;
  for (let l = 1; l <= 3; l++) for (let i = 0; i < 24; i++) { const q = s.generate(mulberry32(4000 + i * 17 + l), l); n++; if (q.figure) fig++; if (q.worked) worked++; if (q.figure || q.worked) any++; }
  rows.push({ id: s.id, name: s.name, year: s.year, strand: s.strand, q: n, fig, worked, any });
}
const pct = (a: number, n: number) => `${Math.round((a / n) * 100)}%`;
const status = (r: (typeof rows)[number]) => (r.any === r.q ? "all" : r.any / r.q >= 0.5 ? "most" : r.any > 0 ? "some" : "none");
const counts = { all: 0, most: 0, some: 0, none: 0 };
for (const r of rows) counts[status(r) as keyof typeof counts]++;
const out = [
  "# Worked examples and pictures: coverage",
  "",
  "Generated by `npm run audit:worked`. For every maths topic: the share of questions that come with a picture, either a figure shown with the question or the method drawn in the solution (column layout, number line with hops, bar model, grid, bus stop, chunking, table and so on).",
  "",
  `Topics: ${rows.length}. Picture on every question: ${counts.all}. On most: ${counts.most}. On some: ${counts.some}. None: ${counts.none}.`,
  "",
  "Topics with no picture are mostly ones where the working is symbolic (algebra, calculus), where the steps written out are the method, or ones still to do (see task 40 in the roadmap).",
  "",
  "| Topic | Year | Strand | With the question | Method drawn | Any picture | Status |",
  "|---|---|---|---|---|---|---|",
  ...rows.sort((a, b) => a.year - b.year || a.strand.localeCompare(b.strand) || a.name.localeCompare(b.name)).map((r) => `| ${r.name} (\`${r.id}\`) | ${r.year} | ${r.strand} | ${pct(r.fig, r.q)} | ${pct(r.worked, r.q)} | ${pct(r.any, r.q)} | ${status(r)} |`),
  "",
].join("\n");
writeFileSync(new URL("../docs/WORKED_EXAMPLES.md", import.meta.url), out);
console.log(counts, "none:", rows.filter((r) => status(r) === "none").map((r) => `${r.id}(Y${r.year})`).join(" "));
