export function letterName(name: string) {
  let width = 16;
  const strokes: { x: number; path: string; y?: number }[] = [];
  for (const character of name.normalize("NFC").match(/\P{M}\p{M}*|\p{M}+/gu) ?? []) {
    if (/\s/.test(character)) {
      width += 10;
      continue;
    }
    const [base, ...accents] = character.normalize("NFD");
    const letter = letters[base];
    if (!letter || accents.some((mark) => !marks[mark])) return undefined;
    strokes.push({ x: width, path: letter[1] });
    for (const mark of accents) {
      strokes.push({ x: width + (letter[0] - 14) / 2, path: marks[mark], y: base === base.toUpperCase() && mark !== "\u0327" ? -11 : 0 });
    }
    width += letter[0];
  }
  return { strokes, width: width + 12 };
}
